//! Real configured AppState, genuine Ready exports, operator HTTP router and
//! managed encrypted loopback control nodes. This is not full-instance restore,
//! physical-site acceptance, process-kill survival or Authority activation.
#![cfg(target_os = "linux")]
#[path = "fixtures/recovery_publication_operator.rs"]
mod fixture;

