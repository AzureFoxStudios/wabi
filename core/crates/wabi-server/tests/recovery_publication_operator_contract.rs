fn historical(job: &Value, capture: &str) -> Value {
    assert_eq!(job["phase"], "historical", "{job}");
    assert!(job["failureCode"].is_null());
    let receipt = job["historicalReceipt"].clone();
    assert_eq!(receipt["operationId"], uuid::Uuid::parse_str(capture).unwrap().simple().to_string());
    assert_eq!(receipt["metadataCommitted"], true);
    assert_eq!(receipt["quorumAvailable"], false);
    assert_eq!(receipt["fullInstanceReady"], false);
    assert_eq!(receipt["canonicalWriterPermitted"], false);
    for name in ["manifestSha256", "commandFingerprint"] {
        assert_eq!(receipt[name].as_str().unwrap().len(), 64);
    }
    receipt
}
async fn refused(app: &axum::Router, secret: &str, capture: &str) {
    let (code, refusal) = request(app, "POST", PUBLICATIONS, "127.0.0.1:33001", Some(secret),
        Body::from(json!({"captureJobId":capture}).to_string())).await;
    assert_eq!(code, StatusCode::SERVICE_UNAVAILABLE, "{refusal}");
    let job = finished(app, secret, capture).await;
    assert_eq!(job["phase"], "failed", "{job}");
    assert_eq!(job["failureCode"], "publication_indeterminate");
    assert!(job["historicalReceipt"].is_null());
    assert_eq!(status(app, secret).await["accepting"], false);
}
async fn startup_refused(config: &wabi_server::config::ServerConfig) {
    assert!(AppState::new(config.clone()).await.is_err(), "invalid configured startup admitted");
    // An error alone does not prove the opened Authority's storage is stopped.
    let _drained = stopped_lock(&Path::new(&config.data_dir).join("wabidb/.lock")).await;
}

/// This binary has exactly one test, run serially by the remote coordinator.
/// No live user data, inherited operator inputs or fixed private keys are used.
#[tokio::test(flavor = "multi_thread", worker_threads = 2)]
async fn configured_genuine_publication_preserves_original_receipt_and_refuses_unsafe_retry() {
    let mut env = Environment::new();
    let root = Root::new();
    let secret = uuid::Uuid::new_v4().simple().to_string();
    env.set("WABI_OPERATOR_SECRET", &secret);
    let checkpoints = root.path().join("checkpoints");
    private(&checkpoints);
    env.set("WABI_CHECKPOINT_DIR", &checkpoints);
    let identity = age::x25519::Identity::generate();
    env.set("WABI_CHECKPOINT_RECIPIENT", identity.to_public().to_string());
    env.set("WABI_CHECKPOINT_SOURCE_CONTEXT", "1");
    for (name, value) in [
        ("WABI_CHECKPOINT_DRAIN_SECONDS", "3"), ("WABI_CHECKPOINT_COPY_SECONDS", "10"),
        ("WABI_CHECKPOINT_MAX_ENTRIES", "10000"), ("WABI_CHECKPOINT_MAX_BYTES", "33554432"),
        ("WABI_CHECKPOINT_MAX_PATH_BYTES", "1048576"), ("WABI_CHECKPOINT_STORAGE_BYTES", "268435456"),
        ("WABI_CHECKPOINT_MIN_FREE_BYTES", "67108864")
    ] { env.set(name, value); }
    let config = config(root.path());
    let initial = Arc::new(AppState::new(config.clone()).await.unwrap());
    let app = build_app_router(initial.clone());
    let disabled = status(&app, &secret).await;
    assert_eq!(disabled["enabled"], false);
    assert_eq!(disabled["accepting"], false);
    assert_eq!(request(&app, "POST", PUBLICATIONS, "127.0.0.1:33001", Some(&secret),
        Body::from("{}")).await.0, StatusCode::SERVICE_UNAVAILABLE);

    // Real durable application records and an actually registered upload.
    let user = initial.wdb.create_user("publication_owner", None, "generated-fixture-hash").await.unwrap();
    initial.claim_ownership(user as i64, "publication_owner").await.unwrap();
    let channel = initial.wdb.create_channel("Publication contract", ChannelKind::Text, user, false).await.unwrap();
    initial.wdb.add_channel_member(&channel, user, MemberRole::Owner).await.unwrap();
    let message = initial.wdb.send_message(&channel, user, "genuine capture content", false, &[]).await.unwrap();
    // Incompressible generated bytes exercise actual multi-object ciphertext.
    let mut seed = 0x517a_84d3_094e_632bu64;
    let payload: Vec<u8> = (0..160 * 1024).map(|_| {
        seed ^= seed << 13; seed ^= seed >> 7; seed ^= seed << 17; seed as u8
    }).collect();
    initial.upload_registry.publish_bytes(Path::new(&config.uploads_dir), initial.wdb.engine(),
        "publication-fixture.bin", "publication-fixture.bin", None, None, Some(user as i64),
        wabi_server::upload_registry::UploadKind::Other, &payload).await.unwrap();
    let first = capture(&app, &initial, &secret).await;
    let (code, context) = request(&app, "GET", &format!("/api/operator/checkpoints/{}/source-context", first.id),
        "127.0.0.1:33001", Some(&secret), Body::empty()).await;
    assert_eq!(code, StatusCode::OK);
    let signed: SignedSourceContext = serde_json::from_value(context).unwrap();
    let community = initial.community_roster.community_id().to_string();
    let verified = signed.verify(&community, &config.node_id).unwrap();
    let capture_receipt = first.receipt.as_ref().unwrap();
    assert_eq!(verified.claims().archive_sha256, capture_receipt.encrypted_archive_sha256);
    assert_eq!(verified.claims().inventory_sha256, capture_receipt.inventory_sha256);
    assert_eq!(verified.claims().applied_commit_seq, capture_receipt.applied_commit_seq);
    let source_path = checkpoints.join(format!("{}.source-context.json", first.id));
    let archive_path = checkpoints.join(format!("{}.age", first.id));
    let original_source = fs::read(&source_path).unwrap();
    let original_archive = fs::read(&archive_path).unwrap();
    let source_inode = inode(&source_path);
    let archive_inode = inode(&archive_path);
    let engine_lock = Path::new(&config.data_dir).join("wabidb/.lock");
    let engine_inode = inode(&engine_lock);

    // The manager retains sixteen entries. Evict the first via real captures,
    // never by editing or inventing a Ready job/receipt on disk.
    let mut last = first.clone();
    for _ in 0..16 { last = capture(&app, &initial, &secret).await; }
    assert!(!initial.checkpoint_jobs.status().jobs.iter().any(|job| job.id == first.id));
    assert!(checkpoints.join(format!("{}.json", first.id)).is_file());
    halt(initial, app, None).await;
    assert_eq!(inode(&engine_lock), engine_inode);

    let mut policies = policies(root.path(), &community, &config.node_id);
    let policy_path = root.path().join("publisher.json");
    let original = policies[0].clone();
    // Actual startup refusals, no direct injection of the private publisher.
    fs::write(&policy_path, b"invalid private configuration").unwrap();
    use std::os::unix::fs::PermissionsExt;
    fs::set_permissions(&policy_path, fs::Permissions::from_mode(0o600)).unwrap();
    env.set("WABI_RECOVERY_PUBLISHER_CONFIG", &policy_path);
    startup_refused(&config).await;
    let mut mismatch = original.clone();
    mismatch.source_node_id = "different-authority".into();
    write_policy(&policy_path, &mismatch);
    startup_refused(&config).await;
    write_policy(&policy_path, &original);
    env.set("WABI_CHECKPOINT_SOURCE_CONTEXT", "0");
    startup_refused(&config).await;
    env.set("WABI_CHECKPOINT_SOURCE_CONTEXT", "1");

    let mut followers = Vec::new();
    for policy in &policies[1..] {
        let path = policy.control_directory.parent().unwrap().join("node.json");
        write_policy(&path, policy);
        followers.push(RecoveryRuntime::start(load(&path).unwrap()).await.unwrap());
    }
    let state = Arc::new(AppState::new(config.clone()).await.unwrap());
    assert_eq!(state.community_roster.community_id(), community);
    assert!(!state.checkpoint_jobs.status().jobs.iter().any(|job| job.id == first.id),
        "configured publication must exercise persisted Ready fallback outside UI history");
    assert!(state.wdb.get_message_typed(&message).await.unwrap().is_some());
    let app = build_app_router(state.clone());
    leader(&followers, Some(1)).await;
    let enabled = status(&app, &secret).await;
    assert_eq!(enabled["enabled"], true);
    assert_eq!(enabled["accepting"], true);
    assert_eq!(enabled["jobs"], json!([]));
    let mut owned_inodes = Vec::new();
    for policy in &policies {
        for path in [policy.control_directory.join(".runtime.lock"), policy.control_directory.join(".lock"),
            policy.material_directory.join(".lock"), policy.identity_directory.join("recovery.key")] {
            owned_inodes.push((path.clone(), inode(&path)));
        }
    }
    // Auth rejection precedes polling a body which never produces bytes.
    for (peer, supplied) in [("127.0.0.1:33001", None), ("127.0.0.1:33001", Some("wrong")),
        ("100.64.0.2:33001", Some(secret.as_str()))] {
        let never = futures::stream::pending::<Result<axum::body::Bytes, std::convert::Infallible>>();
        assert_eq!(request(&app, "POST", PUBLICATIONS, peer, supplied, Body::from_stream(never)).await.0,
            StatusCode::FORBIDDEN);
    }
    for body in ["{}".to_string(), "not JSON".to_string(),
        json!({"captureJobId":first.id, "nodeId":2}).to_string(),
        format!("{{\"captureJobId\":\"{}\",\"captureJobId\":\"{}\"}}", first.id, first.id),
        json!({"captureJobId":uuid::Uuid::parse_str(&first.id).unwrap().simple().to_string()}).to_string()] {
        assert_eq!(request(&app, "POST", PUBLICATIONS, "127.0.0.1:33001", Some(&secret),
            Body::from(body)).await.0, StatusCode::BAD_REQUEST);
    }
    assert_eq!(request(&app, "POST", PUBLICATIONS, "127.0.0.1:33001", Some(&secret),
        Body::from(vec![b' '; 1025])).await.0, StatusCode::PAYLOAD_TOO_LARGE);
    assert_eq!(status(&app, &secret).await["jobs"], json!([]));

    // HTTP acceptance waits for the durable original intent. A paused
    // instance queues the owned worker without acknowledging volatile work.
    let pause = state.instance_operations.quiesce().await.unwrap();
    let operation = uuid::Uuid::parse_str(&first.id).unwrap().simple().to_string();
    let intent_path = policies[0].control_directory.join(format!("publication-{operation}-capture.json"));
    let submitting_app = app.clone();
    let submitting_secret = secret.clone();
    let submitting_capture = first.id.clone();
    let submitting = tokio::spawn(async move {
        request(&submitting_app, "POST", PUBLICATIONS, "127.0.0.1:33001", Some(&submitting_secret),
            Body::from(json!({"captureJobId":submitting_capture}).to_string())).await
    });
    tokio::time::timeout(Duration::from_secs(2), async {
        while status(&app, &secret).await["activeCaptureId"] != first.id {
            tokio::task::yield_now().await;
        }
    }).await.expect("publication did not retain its queued worker");
    assert!(!submitting.is_finished(), "volatile admission returned before journal durability");
    assert!(!intent_path.exists(), "paused source work unexpectedly published intent");
    assert_eq!(request(&app, "POST", PUBLICATIONS, "127.0.0.1:33001", Some(&secret),
        Body::from(json!({"captureJobId":last.id}).to_string())).await.0, StatusCode::CONFLICT);
    drop(pause);
    let (code, queued) = submitting.await.unwrap();
    assert_eq!(code, StatusCode::ACCEPTED, "{queued}");
    let intent: Value = serde_json::from_slice(&fs::read(&intent_path).unwrap()).unwrap();
    assert_eq!(intent["operationId"], operation);
    assert_eq!(intent["body"]["phase"], "capture");
    assert_eq!(intent["body"]["payload"], serde_json::to_value(&signed).unwrap());
    assert_eq!(queued["operationId"], operation);
    assert_eq!(queued["fullInstanceReady"], false);
    assert_eq!(queued["canonicalWriterPermitted"], false);
    let receipt = historical(&finished(&app, &secret, &first.id).await, &first.id);
    assert_eq!(historical(&publish(&app, &secret, &first.id).await, &first.id), receipt);
    // Cancelling a real operator HTTP waiter cannot discard the original
    // supervised worker. Reconcile the already durable same operation;
    // this exercises waiter cancellation, not a mid-read or process crash.
    let pause = state.instance_operations.quiesce().await.unwrap();
    let cancelled_app = app.clone();
    let cancelled_secret = secret.clone();
    let cancelled_capture = first.id.clone();
    let cancelled = tokio::spawn(async move {
        request(&cancelled_app, "POST", PUBLICATIONS, "127.0.0.1:33001", Some(&cancelled_secret),
            Body::from(json!({"captureJobId":cancelled_capture}).to_string())).await
    });
    tokio::time::timeout(Duration::from_secs(2), async {
        while status(&app, &secret).await["activeCaptureId"] != first.id
            || state.instance_operations.waiting_operations() == 0 {
            tokio::task::yield_now().await;
        }
    }).await.expect("original retry did not retain queued instance admission");
    cancelled.abort();
    assert!(cancelled.await.unwrap_err().is_cancelled());
    assert_eq!(status(&app, &secret).await["activeCaptureId"], first.id);
    assert_eq!(request(&app, "POST", PUBLICATIONS, "127.0.0.1:33001", Some(&secret),
        Body::from(json!({"captureJobId":first.id}).to_string())).await.0, StatusCode::CONFLICT);
    drop(pause);
    assert_eq!(historical(&finished(&app, &secret, &first.id).await, &first.id), receipt);
    let operation = uuid::Uuid::parse_str(&first.id).unwrap().simple().to_string();
    let replicated = tokio::time::timeout(Duration::from_secs(10), async {
        loop {
            let left = followers[0].control_state().await.unwrap();
            let right = followers[1].control_state().await.unwrap();
            if let (Some(left), Some(right)) = (left.checkpoints.get(&operation), right.checkpoints.get(&operation)) {
                assert_eq!(left, right);
                assert_eq!(left.command.manifest_sha256(), receipt["manifestSha256"].as_str().unwrap());
                assert_eq!(left.command.fingerprint().unwrap(), receipt["commandFingerprint"].as_str().unwrap());
                return serde_json::to_value(left).unwrap();
            }
            tokio::time::sleep(Duration::from_millis(20)).await;
        }
    }).await.expect("actual follower projections did not contain original checkpoint command");
    assert_eq!(replicated["command"]["manifest"]["source"], serde_json::to_value(&signed).unwrap());
    assert!(replicated["command"]["manifest"]["objects"].as_array().unwrap().len() > 2,
        "genuine archive must cross actual material object boundaries");
    halt(state, app, Some(&policies[0])).await;
    let successor = leader_from_allowed(&followers, &[2, 3]).await;
    assert!(successor == 2 || successor == 3);
    policies[0].initialize = false;
    write_policy(&policy_path, &policies[0]);
    let state = Arc::new(AppState::new(config.clone()).await.unwrap());
    let app = build_app_router(state.clone());
    leader(&followers, Some(successor)).await;
    assert_eq!(status(&app, &secret).await["jobs"], json!([]), "HTTP history must reset on restart");
    assert_eq!(historical(&publish(&app, &secret, &first.id).await, &first.id), receipt);
    assert_eq!(fs::read(&source_path).unwrap(), original_source);
    assert_eq!(fs::read(&archive_path).unwrap(), original_archive);
    assert_eq!(inode(&source_path), source_inode);
    assert_eq!(inode(&archive_path), archive_inode);
    // A fresh genuine Ready operation on the configured control follower must
    // refuse rather than create another collector/writer or retry identity.
    refused(&app, &secret, &last.id).await;
    halt(state, app, Some(&policies[0])).await;
    for node in followers { node.shutdown().await.unwrap(); }
    let saved = recorded(&policies[0]).await;
    assert_eq!(saved.as_object().unwrap().len(), 1);
    assert_eq!(saved[&operation], replicated);

    // Original historical metadata survives without a live majority. A new
    // operation cannot turn that historical receipt into present availability.
    let state = Arc::new(AppState::new(config.clone()).await.unwrap());
    let app = build_app_router(state.clone());
    assert_eq!(historical(&publish(&app, &secret, &first.id).await, &first.id), receipt);
    refused(&app, &secret, &last.id).await;
    halt(state, app, Some(&policies[0])).await;
    assert_eq!(recorded(&policies[0]).await, saved);

    // A real paused instance must not leave the HTTP admission waiter
    // unbounded. Use the operator's valid shortest budget (3 * 1 second),
    // retaining the actual queued original worker through refusal and drain.
    let original_timeout = policies[0].work_timeout_seconds;
    policies[0].work_timeout_seconds = 1;
    write_policy(&policy_path, &policies[0]);
    let state = Arc::new(AppState::new(config.clone()).await.unwrap());
    let app = build_app_router(state.clone());
    let pause = state.instance_operations.quiesce().await.unwrap();
    let submitting_app = app.clone();
    let submitting_secret = secret.clone();
    let submitting_capture = first.id.clone();
    let submitting = tokio::spawn(async move {
        request(&submitting_app, "POST", PUBLICATIONS, "127.0.0.1:33001", Some(&submitting_secret),
            Body::from(json!({"captureJobId":submitting_capture}).to_string())).await
    });
    tokio::time::timeout(Duration::from_secs(2), async {
        while status(&app, &secret).await["activeCaptureId"] != first.id {
            tokio::task::yield_now().await;
        }
    }).await.expect("bounded waiter did not queue original publication");
    let (code, refusal) = tokio::time::timeout(Duration::from_secs(5), submitting)
        .await.expect("HTTP admission waiter exceeded its monotonic budget").unwrap();
    assert_eq!(code, StatusCode::SERVICE_UNAVAILABLE, "{refusal}");
    assert_eq!(status(&app, &secret).await["accepting"], false);
    assert_eq!(status(&app, &secret).await["activeCaptureId"], first.id);
    let weak = Arc::downgrade(&state);
    let io = state.sio.write().unwrap().take();
    if let Some(io) = io { io.close().await; }
    state.checkpoint_jobs.shutdown_peer_verification().await;
    state.tailcat.shutdown().await;
    drop(app);
    drop(state);
    assert!(weak.upgrade().is_some(), "timed-out waiter released its queued Authority owner");
    let probe = fs::OpenOptions::new().read(true).write(true).open(&engine_lock).unwrap();
    assert_eq!(inode(&engine_lock), engine_inode);
    assert!(!fs4::fs_std::FileExt::try_lock_exclusive(&probe).unwrap(),
        "queued publication lost the original Authority storage lease");
    drop(probe);
    drop(pause);
    tokio::time::timeout(Duration::from_secs(20), async {
        while weak.upgrade().is_some() { tokio::time::sleep(Duration::from_millis(10)).await; }
    }).await.expect("refused queued publication did not actually drain after pause release");
    let _engine_drained = stopped_lock(&engine_lock).await;
    drop(_engine_drained);
    for path in [policies[0].control_directory.join(".runtime.lock"),
        policies[0].control_directory.join(".lock"), policies[0].material_directory.join(".lock")] {
        let _drained = stopped_lock(&path).await;
    }
    assert_eq!(recorded(&policies[0]).await, saved);
    policies[0].work_timeout_seconds = original_timeout;
    write_policy(&policy_path, &policies[0]);

    // Genuine writer fence vetoes even historical retry, and remains durable
    // across startup. The fixture never removes a fence to admit a writer.
    let state = Arc::new(AppState::new(config.clone()).await.unwrap());
    let app = build_app_router(state.clone());
    state.wdb.engine().fence_local_writer().await.unwrap();
    refused(&app, &secret, &first.id).await;
    halt(state, app, Some(&policies[0])).await;
    startup_refused(&config).await;
    assert_eq!(recorded(&policies[0]).await, saved);
    assert_eq!(inode(&engine_lock), engine_inode);
    for (path, original) in owned_inodes { assert_eq!(inode(&path), original); }
    for policy in &policies {
        let _runtime = stopped_lock(&policy.control_directory.join(".runtime.lock")).await;
        let _control = stopped_lock(&policy.control_directory.join(".lock")).await;
        let _material = stopped_lock(&policy.material_directory.join(".lock")).await;
    }
    root.completed();
}
